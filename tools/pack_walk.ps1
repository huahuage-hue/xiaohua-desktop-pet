param(
  [string]$FrameDir = (Join-Path $PSScriptRoot '..\psd\raw\gen\puppet\frames'),
  [string]$OutPng = (Join-Path $PSScriptRoot '..\assets\xiaohua_walk.png'),
  [string]$OutJs = (Join-Path $PSScriptRoot '..\assets\xiaohua_walk.js')
)
Add-Type -AssemblyName System.Drawing
$ErrorActionPreference = 'Stop'
$fw = 720; $fh = 1280; $cols = 4; $rows = 2
$sheet = New-Object System.Drawing.Bitmap -ArgumentList ($fw * $cols), ($fh * $rows), ([System.Drawing.Imaging.PixelFormat]::Format32bppArgb)
$g = [System.Drawing.Graphics]::FromImage($sheet)
$g.Clear([System.Drawing.Color]::Transparent)
$g.InterpolationMode = [System.Drawing.Drawing2D.InterpolationMode]::HighQualityBicubic
$g.PixelOffsetMode = [System.Drawing.Drawing2D.PixelOffsetMode]::HighQuality
for ($p = 0; $p -lt 8; $p++) {
  $img = [System.Drawing.Bitmap]::FromFile((Join-Path $FrameDir ("frame_{0}.png" -f $p)))
  $x = ($p % $cols) * $fw; $y = [Math]::Floor($p / $cols) * $fh
  $g.DrawImage($img, $x, $y, $fw, $fh)
  $img.Dispose()
}
$g.Dispose()
$sheet.Save($OutPng, [System.Drawing.Imaging.ImageFormat]::Png)
$sheet.Dispose()
$js = @"
/* generated by tools/pack_walk.ps1 - 8-frame side walk sprite, 4x2 */
window.XH_WALK = {
  src: 'assets/xiaohua_walk.png',
  cols: 4, rows: 2, frames: 8,
  fw: 720, fh: 1280,
  lw: 1200, lh: 2133,
  fps: 8,
  head: [560, 150]
};
"@
Set-Content -LiteralPath $OutJs -Value $js -Encoding UTF8
'packed -> ' + $OutPng
